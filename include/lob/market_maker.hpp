#pragma once
// Phase 4: a single market-maker agent, holding its own MatchingEngine&
// and managing its own two-sided quote directly. This is NOT a full
// Avellaneda-Stoikov implementation -- see each config field's comment
// for exactly where this simplifies, and DESIGN_DECISIONS.md for why.

#include <cstdint>
#include <deque>

#include "lob/matching_engine.hpp"

namespace lob {

struct MarketMakerConfig {
    Quantity quote_size = 10;      // size posted on EACH side, every quote
    Quantity max_inventory = 100;  // hard cap on |inventory| -- see below

    // base_half_spread: ticks from the (possibly skewed) reference price
    // to each quote, before any adverse-selection widening.
    Price base_half_spread = 2;

    // inventory_skew_factor: ticks the reference price shifts PER UNIT
    // of inventory, in the direction that encourages reducing it (long
    // inventory shifts both quotes down, to attract sellers at the bid
    // and discourage buyers at... no: to attract fills that REDUCE
    // inventory -- see market_maker.cpp for the worked sign). This is a
    // LINEAR proxy for inventory risk, not Avellaneda-Stoikov's
    // exponential-utility/time-to-horizon-derived skew -- that's a
    // materially different (and more principled) derivation, named here
    // as future work rather than approximated further.
    double inventory_skew_factor = 0.0;

    // Adverse-selection widening: a FIXED trigger-and-decay window, not
    // a continuous or exponentially-decaying signal. If
    // run_over_fill_threshold consecutive fills on the SAME side land
    // within run_over_window_ns of each other, quotes widen (half-spread
    // multiplied by adverse_selection_widen_factor) for widen_duration_ns.
    double adverse_selection_widen_factor = 2.0;
    int run_over_fill_threshold = 3;
    std::uint64_t run_over_window_ns = 1'000'000'000;  // 1 second
    std::uint64_t widen_duration_ns = 2'000'000'000;   // 2 seconds
};

struct MarketMakerState {
    Quantity inventory = 0;     // signed: positive = long, negative = short
    double avg_cost = 0.0;      // meaningful only while inventory != 0
    double realized_pnl = 0.0;  // cumulative, average-cost method -- see .cpp
    OrderId bid_order_id = 0;   // 0 = no live bid quote
    OrderId ask_order_id = 0;   // 0 = no live ask quote
    bool widened = false;
    std::uint64_t widen_until_ns = 0;
};

class MarketMakerAgent {
public:
    // first_order_id: the first id this agent will use for its own
    // quotes; it increments a private counter from there for every
    // subsequent quote it posts. The CALLER is responsible for choosing
    // an id range that never overlaps with any other order flow sharing
    // the same MatchingEngine (the same discipline Phase 3's CSV reader
    // already requires of external order ids) -- this agent does not
    // itself detect or guard against a collision with another
    // participant's id space.
    MarketMakerAgent(MatchingEngine& engine, MarketMakerConfig config, OrderId first_order_id);

    // Recomputes the desired bid/ask from current state + the engine's
    // own midprice(), cancels and reposts whichever side(s) need to
    // change, and withdraws (without reposting) any side that has hit
    // its inventory limit. If MatchingEngine::midprice() is unavailable
    // (one or both sides of the book empty), this is a no-op: existing
    // resting quotes are left exactly as they are rather than guessing
    // a reference price. Any trade generated by THIS call's own
    // submit() (an immediate self-cross) is applied to state directly,
    // inline -- see .cpp; it does not go through onFill().
    void onTick(std::uint64_t timestamp_ns);

    // Called by an external integration point (MarketSession) when a
    // trade elsewhere in the engine was matched against one of this
    // agent's OWN resting orders. `side_filled` is the side of the
    // AGENT's order that got hit (Buy means the agent bought).
    void onFill(Side side_filled, Price price, Quantity qty, std::uint64_t timestamp_ns);

    const MarketMakerState& state() const { return state_; }

    double unrealizedPnl(double midprice) const;
    double totalPnl(double midprice) const;

private:
    MatchingEngine& engine_;
    MarketMakerConfig config_;
    MarketMakerState state_;
    OrderId next_order_id_;
    std::deque<std::pair<Side, std::uint64_t>> recent_fills_;  // (side, timestamp_ns)

    void recordFill(Side side_filled, Price price, Quantity qty, std::uint64_t timestamp_ns);
    void updateAdverseSelection(Side side_filled, std::uint64_t timestamp_ns);
    void applyPnlUpdate(Side side_filled, Price price, Quantity qty);
};

}  // namespace lob
